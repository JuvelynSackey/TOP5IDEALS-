-- =============================================================================
-- Top5Ideals 0300 — Phone catalogue (brands and models).
-- Data is loaded by supabase/seed.sql (idempotent) and maintained by admins.
-- =============================================================================

create table public.brands (
  id smallint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 60),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  sort_order smallint not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.phone_models (
  id integer generated by default as identity primary key,
  brand_id smallint not null references public.brands (id),
  name text not null check (char_length(name) between 1 and 80),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  release_year smallint check (release_year is null or release_year between 2000 and 2100),
  storage_options_gb integer[] not null default '{}',
  ram_options_gb integer[] not null default '{}',
  -- Whether the OS exposes a battery-health percentage (e.g. iPhone).
  battery_health_supported boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (brand_id, name)
);
create index phone_models_brand_idx on public.phone_models (brand_id) where is_active;

create trigger brands_updated_at before update on public.brands for each row execute function public.set_updated_at();
create trigger phone_models_updated_at before update on public.phone_models for each row execute function public.set_updated_at();

alter table public.brands enable row level security;
alter table public.phone_models enable row level security;

create policy "brands are public" on public.brands for select using (true);
create policy "admins insert brands" on public.brands for insert to authenticated with check (public.is_admin());
create policy "admins update brands" on public.brands for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "models are public" on public.phone_models for select using (true);
create policy "admins insert models" on public.phone_models for insert to authenticated with check (public.is_admin());
create policy "admins update models" on public.phone_models for update to authenticated using (public.is_admin()) with check (public.is_admin());

revoke all on public.brands, public.phone_models from anon, authenticated;
grant select on public.brands, public.phone_models to anon, authenticated;
grant insert (name, slug, sort_order, is_active), update (name, slug, sort_order, is_active) on public.brands to authenticated;
grant insert (brand_id, name, slug, release_year, storage_options_gb, ram_options_gb, battery_health_supported, is_active),
      update (name, slug, release_year, storage_options_gb, ram_options_gb, battery_health_supported, is_active)
  on public.phone_models to authenticated;
