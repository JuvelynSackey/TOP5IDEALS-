-- Submit a draft for publication, or resubmit a rejected listing.
create or replace function public.publish_listing(p_listing_id uuid)
returns public.listings
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := app_private.require_user(true);
  v_listing public.listings;
  v_auto boolean;
  v_verified boolean;
begin
  perform app_private.enforce_rate_limit(v_uid, 'listing_publish', 30, interval '1 day');
  v_listing := app_private.owned_listing_for_update(p_listing_id, v_uid);

  if not (v_listing.status = 'draft'
          or (v_listing.status in ('published', 'paused') and v_listing.moderation_status = 'rejected')) then
    perform app_private.fail('invalid_state', 'Only drafts and rejected listings can be submitted.');
  end if;
  if v_listing.condition is null or v_listing.price_minor is null or v_listing.region_id is null or v_listing.city is null then
    perform app_private.fail('listing_incomplete', 'Add the condition, price and location before publishing.');
  end if;
  if not exists (select 1 from public.listing_images where listing_id = v_listing.id and is_primary) then
    perform app_private.fail('listing_incomplete', 'Add at least one photo and choose a primary photo.');
  end if;

  v_auto := app_private.setting_bool('auto_approve_verified_sellers', false);
  select verification_status = 'verified' into v_verified from public.profiles where id = v_uid;

  if v_auto and v_verified then
    update public.listings
      set status = 'published', moderation_status = 'approved', published_at = coalesce(published_at, now())
      where id = v_listing.id
      returning * into v_listing;
    insert into public.listing_moderation_events (listing_id, actor_id, decision, reason)
      values (v_listing.id, null, 'auto_approved', 'Verified seller auto-approval policy');
    perform app_private.log_audit(v_uid, 'listing.auto_approved', 'listing', v_listing.id::text, '{}');
  else
    update public.listings
      set status = case when status = 'draft' then 'published'::public.listing_status else status end,
          moderation_status = 'pending_review'
      where id = v_listing.id
      returning * into v_listing;
    insert into public.listing_moderation_events (listing_id, actor_id, decision)
      values (v_listing.id, v_uid, 'submitted');
    perform app_private.log_audit(v_uid, 'listing.submitted', 'listing', v_listing.id::text, '{}');
  end if;
  return v_listing;
end;
$$;

