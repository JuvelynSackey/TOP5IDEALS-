create or replace function public.format_storage(p_gb integer)
returns text
language sql
immutable
as $$
  select case
    when p_gb is null then null
    when p_gb >= 1024 and p_gb % 1024 = 0 then (p_gb / 1024)::text || 'TB'
    else p_gb::text || 'GB'
  end;
$$;

create or replace function public.listing_is_public(p_status public.listing_status, p_moderation public.moderation_status)
returns boolean
language sql
immutable
as $$
  select p_moderation = 'approved' and p_status in ('published', 'paused', 'reserved', 'sold', 'swapped');
$$;

-- Invoker-rights trigger: current_user tells us whether a client (authenticated)
-- or a trusted SECURITY DEFINER function is writing.
create or replace function public.listings_before_write()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_is_client boolean := current_user in ('authenticated', 'anon');
  v_brand text;
  v_model text;
  v_region text;
  v_material boolean;
begin
  select name into v_brand from public.brands where id = new.brand_id;
  if new.model_id is not null then
    select name into v_model from public.phone_models where id = new.model_id and brand_id = new.brand_id;
    if v_model is null then
      perform app_private.fail('validation_failed', 'The selected model does not belong to the selected brand.');
    end if;
  end if;
  select name into v_region from public.regions where id = new.region_id;

  if tg_op = 'INSERT' then
    new.slug_key := app_private.random_key(8);
    if v_is_client then
      new.status := 'draft';
      new.moderation_status := 'not_submitted';
      new.published_at := null;
    end if;
  else
    new.slug_key := old.slug_key;
    new.created_at := old.created_at;
    if v_is_client then
      if old.status in ('reserved', 'sold', 'swapped', 'archived') then
        perform app_private.fail('listing_locked', 'This listing can no longer be edited.');
      end if;
      v_material := (new.brand_id, new.model_id, new.custom_model, new.variant, new.title, new.description,
                     new.storage_gb, new.ram_gb, new.color, new.condition, new.battery_health_status,
                     new.battery_health, new.device_checks, new.network_lock, new.accessories,
                     new.defects, new.warranty_details)
                    is distinct from
                    (old.brand_id, old.model_id, old.custom_model, old.variant, old.title, old.description,
                     old.storage_gb, old.ram_gb, old.color, old.condition, old.battery_health_status,
                     old.battery_health, old.device_checks, old.network_lock, old.accessories,
                     old.defects, old.warranty_details);
      -- Material edits to an approved listing must be re-reviewed.
      if v_material and old.moderation_status = 'approved' then
        new.moderation_status := 'pending_review';
      end if;
    end if;
  end if;

  if new.title is null or btrim(new.title) = '' then
    new.title := concat_ws(' ', v_brand, coalesce(v_model, new.custom_model), public.format_storage(new.storage_gb));
  end if;
  new.title := btrim(new.title);

  new.slug := left(app_private.slugify(concat_ws(' ', coalesce(v_model, new.custom_model), public.format_storage(new.storage_gb), new.city)), 80);
  new.slug := trim(both '-' from new.slug);
  if new.slug = '' then
    new.slug := 'phone';
  end if;

  new.search_vector :=
    setweight(to_tsvector('simple', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('simple', concat_ws(' ', v_brand, v_model, new.custom_model)), 'A') ||
    setweight(to_tsvector('simple', concat_ws(' ', new.variant, new.color, lower(public.format_storage(new.storage_gb)),
                                              case when new.ram_gb is not null then new.ram_gb || 'gb ram' end)), 'B') ||
    setweight(to_tsvector('simple', concat_ws(' ', v_region, new.city, new.area)), 'C') ||
    setweight(to_tsvector('simple', coalesce(new.description, '')), 'D');

  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    new.status_changed_at := now();
  end if;
  return new;
end;
$$;

create trigger listings_before_write before insert or update on public.listings
  for each row execute function public.listings_before_write();
create trigger listings_updated_at before update on public.listings
  for each row execute function public.set_updated_at();

-- Lock a listing the caller owns for a state change.
create or replace function app_private.owned_listing_for_update(p_listing_id uuid, p_uid uuid)
returns public.listings
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_listing public.listings;
begin
  select * into v_listing from public.listings where id = p_listing_id for update;
  if not found or v_listing.seller_id <> p_uid then
    perform app_private.fail('not_found', 'Listing not found.');
  end if;
  return v_listing;
end;
$$;

