create or replace function app_private.assert_listing_editable(p_listing public.listings)
returns void
language plpgsql
as $$
begin
  if p_listing.status in ('reserved', 'sold', 'swapped', 'archived') then
    perform app_private.fail('listing_locked', 'This listing can no longer be edited.');
  end if;
end;
$$;

create or replace function public.add_listing_image(p_listing_id uuid, p_storage_path text, p_width integer default null, p_height integer default null)
returns public.listing_images
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := app_private.require_user(true);
  v_listing public.listings;
  v_count int;
  v_image public.listing_images;
begin
  v_listing := app_private.owned_listing_for_update(p_listing_id, v_uid);
  perform app_private.assert_listing_editable(v_listing);

  if p_storage_path is null or p_storage_path !~ ('^' || v_uid::text || '/' || v_listing.id::text || '/[A-Za-z0-9_-]{8,64}\.(jpg|jpeg|png|webp)$') then
    perform app_private.fail('validation_failed', 'Invalid image path.');
  end if;
  if not exists (
    select 1 from storage.objects o
    where o.bucket_id = 'listing-images' and o.name = p_storage_path
      and (o.owner_id = v_uid::text or o.owner = v_uid)
  ) then
    perform app_private.fail('validation_failed', 'The uploaded image could not be found.');
  end if;

  select count(*) into v_count from public.listing_images where listing_id = v_listing.id;
  if v_count >= 10 then
    perform app_private.fail('too_many_images', 'A listing can have at most 10 photos.');
  end if;

  insert into public.listing_images (listing_id, storage_path, position, is_primary, width, height)
  values (v_listing.id, p_storage_path,
          coalesce((select max(position) + 1 from public.listing_images where listing_id = v_listing.id), 0),
          v_count = 0, p_width, p_height)
  returning * into v_image;

  if v_listing.moderation_status = 'approved' then
    update public.listings set moderation_status = 'pending_review' where id = v_listing.id;
  end if;
  return v_image;
end;
$$;

-- Returns the storage path so the caller can delete the file from storage.
create or replace function public.remove_listing_image(p_image_id uuid)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := app_private.require_user(false);
  v_image public.listing_images;
  v_listing public.listings;
begin
  select * into v_image from public.listing_images where id = p_image_id;
  if not found then
    perform app_private.fail('not_found', 'Image not found.');
  end if;
  v_listing := app_private.owned_listing_for_update(v_image.listing_id, v_uid);
  perform app_private.assert_listing_editable(v_listing);
  if v_listing.status <> 'draft' and (select count(*) from public.listing_images where listing_id = v_listing.id) <= 1 then
    perform app_private.fail('validation_failed', 'A submitted listing must keep at least one photo.');
  end if;

  delete from public.listing_images where id = v_image.id;
  if v_image.is_primary then
    update public.listing_images set is_primary = true
    where id = (select id from public.listing_images where listing_id = v_listing.id order by position, created_at limit 1);
  end if;
  return v_image.storage_path;
end;
$$;

