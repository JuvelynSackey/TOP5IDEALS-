create or replace function public.reorder_listing_images(p_listing_id uuid, p_image_ids uuid[])
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := app_private.require_user(false);
  v_listing public.listings;
begin
  v_listing := app_private.owned_listing_for_update(p_listing_id, v_uid);
  perform app_private.assert_listing_editable(v_listing);
  if (select array_agg(id order by id) from public.listing_images where listing_id = v_listing.id)
     is distinct from (select array_agg(x order by x) from unnest(p_image_ids) x) then
    perform app_private.fail('validation_failed', 'The image list is out of date. Refresh and try again.');
  end if;
  update public.listing_images li set position = o.ord - 1
  from unnest(p_image_ids) with ordinality as o(id, ord)
  where li.id = o.id;
end;
$$;

create or replace function public.set_listing_swap_brands(p_listing_id uuid, p_brand_ids smallint[])
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := app_private.require_user(false);
  v_listing public.listings;
begin
  v_listing := app_private.owned_listing_for_update(p_listing_id, v_uid);
  perform app_private.assert_listing_editable(v_listing);
  if cardinality(coalesce(p_brand_ids, '{}')) > 10 then
    perform app_private.fail('validation_failed', 'Choose at most 10 preferred brands.');
  end if;
  delete from public.listing_swap_brands where listing_id = v_listing.id;
  insert into public.listing_swap_brands (listing_id, brand_id)
  select v_listing.id, b.id from public.brands b where b.id = any (coalesce(p_brand_ids, '{}'));
end;
$$;

