create or replace function public.record_listing_view(p_listing_id uuid, p_anonymous_key text default null)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_key text;
  v_listing public.listings;
begin
  select * into v_listing from public.listings where id = p_listing_id;
  if not found or not public.listing_is_public(v_listing.status, v_listing.moderation_status) then
    return;
  end if;
  if v_uid is not null and v_uid = v_listing.seller_id then
    return;
  end if;
  if v_uid is not null then
    v_key := 'u:' || v_uid::text;
  elsif p_anonymous_key ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    v_key := 'a:' || p_anonymous_key;
  else
    return;
  end if;
  insert into public.listing_views (listing_id, viewer_key, viewer_id)
  values (p_listing_id, v_key, v_uid)
  on conflict (listing_id, viewer_key, view_date) do nothing;
end;
$$;

-- Featured listings must be public at the time they are featured.
create or replace function public.featured_listings_check()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not exists (select 1 from public.listings where id = new.listing_id and status = 'published' and moderation_status = 'approved') then
    perform app_private.fail('invalid_state', 'Only live, approved listings can be featured.');
