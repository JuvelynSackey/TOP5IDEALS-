-- Builds a safe prefix tsquery from free text (only alphanumeric tokens survive).
create or replace function public.build_search_query(p_text text)
returns tsquery
language sql
immutable
as $$
  select case when string_agg(tok, ' & ') is null then null
              else to_tsquery('simple', string_agg(tok || ':*', ' & ')) end
  from (
    select tok
    from unnest(regexp_split_to_array(lower(regexp_replace(coalesce(p_text, ''), '[^[:alnum:]]+', ' ', 'g')), '\s+')) tok
    where tok <> ''
    limit 8
  ) t;
$$;

create or replace function public.search_listings(
  p_query text default null,
  p_brand_ids smallint[] default null,
  p_model_ids integer[] default null,
  p_min_price bigint default null,
  p_max_price bigint default null,
  p_storage integer[] default null,
  p_ram integer[] default null,
  p_conditions public.listing_condition[] default null,
  p_min_battery smallint default null,
  p_region_ids smallint[] default null,
  p_city text default null,
  p_seller_type public.account_type default null,
  p_swap_only boolean default false,
  p_sale_only boolean default false,
  p_verified_only boolean default false,
  p_seller_id uuid default null,
  p_sort text default 'recommended',
  p_limit integer default 24,
  p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $$
declare
  v_query tsquery := public.build_search_query(left(p_query, 200));
  v_limit int := least(greatest(coalesce(p_limit, 24), 1), 48);
  v_offset int := least(greatest(coalesce(p_offset, 0), 0), 5000);
  v_city text := nullif(btrim(left(p_city, 80)), '');
  v_result jsonb;
begin
  if v_city is not null then
    v_city := replace(replace(replace(v_city, '\', '\\'), '%', '\%'), '_', '\_');
  end if;

  with matches as (
    select c.*,
      -- Transparent "recommended" score: text relevance + recency (weekly decay)
      -- + small boosts for verified sellers and reported battery health.
      (case when v_query is null then 0 else ts_rank(l.search_vector, v_query) end * 2.0
        + 1.0 / (1.0 + extract(epoch from (now() - coalesce(c.published_at, c.created_at))) / 604800.0)
        + case when c.seller_verification = 'verified' or c.business_verification = 'verified' then 0.15 else 0 end
        + case when c.battery_health_status = 'reported' then 0.05 else 0 end) as score
    from public.listing_cards c
    join public.listings l on l.id = c.id
    where c.status = 'published' and c.moderation_status = 'approved'
      and (v_query is null or l.search_vector @@ v_query)
      and (p_brand_ids is null or c.brand_id = any (p_brand_ids))
      and (p_model_ids is null or c.model_id = any (p_model_ids))
      and (p_min_price is null or c.price_minor >= p_min_price)
      and (p_max_price is null or c.price_minor <= p_max_price)
      and (p_storage is null or c.storage_gb = any (p_storage))
      and (p_ram is null or c.ram_gb = any (p_ram))
      and (p_conditions is null or c.condition = any (p_conditions))
      and (p_min_battery is null or (c.battery_health_status = 'reported' and c.battery_health >= p_min_battery))
      and (p_region_ids is null or c.region_id = any (p_region_ids))
      and (v_city is null or c.city ilike v_city || '%' or c.area ilike v_city || '%')
      and (p_seller_type is null or c.seller_account_type = p_seller_type)
      and (not coalesce(p_swap_only, false) or c.open_to_swap)
      and (not coalesce(p_sale_only, false) or c.available_for_sale)
      and (not coalesce(p_verified_only, false) or c.seller_verification = 'verified' or c.business_verification = 'verified')
      and (p_seller_id is null or c.seller_id = p_seller_id)
  ),
  ranked as (
    select m.*, row_number() over (
      order by
        case when p_sort = 'price_asc' then m.price_minor end asc nulls last,
        case when p_sort = 'price_desc' then m.price_minor end desc nulls last,
        case when p_sort = 'newest' then coalesce(m.published_at, m.created_at) end desc nulls last,
        m.score desc,
        m.id
    ) as ord
    from matches m
  )
  select jsonb_build_object(
    'total', (select count(*) from matches),
    'items', coalesce((
      select jsonb_agg(to_jsonb(r) - 'score' - 'ord' order by r.ord)
      from ranked r
      where r.ord > v_offset and r.ord <= v_offset + v_limit
    ), '[]'::jsonb)
  )
  into v_result;

  return v_result;
end;
$$;

