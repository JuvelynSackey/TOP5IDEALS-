-- =============================================================================
-- Top5Ideals 0500 — Listings, images, swap preferences, favourites, views,
-- featured listings, public card view and search.
--
-- Listing state is split into two independent axes:
--   status            (seller intent / lifecycle): draft → published ⇄ paused,
--                     published|paused → archived|sold (outside platform),
--                     published → reserved (only by an accepted offer)
--                     → sold | swapped (only by a completed transaction)
--   moderation_status not_submitted → pending_review → approved | rejected
-- A listing is PUBLIC only when moderation_status = 'approved' and status is
-- published/paused/reserved/sold/swapped. It is OFFERABLE (searchable, can
-- receive offers) only when moderation_status = 'approved' and status = 'published'.
-- Status changes go through RPCs; owners may edit content columns directly
-- (column grants + trigger rules) and material edits re-enter moderation.
-- =============================================================================

create or replace function public.valid_device_checks(p jsonb)
returns boolean
language sql
immutable
as $$
  select jsonb_typeof(p) = 'object' and not exists (
    select 1 from jsonb_each_text(p) e
    where e.key not in ('display', 'touch', 'cameras', 'biometrics', 'speakers', 'microphone',
                        'charging', 'wifi_bluetooth', 'cellular', 'buttons')
       or e.value not in ('working', 'faulty', 'not_tested')
  );
$$;

create table public.listings (
  id uuid primary key default gen_random_uuid(),
  -- slug_key, slug and (when blank) title are generated by listings_before_write.
  slug_key text not null default '' unique check (slug_key ~ '^[a-z0-9]{8}$'),
  slug text not null default 'phone' check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  seller_id uuid not null references public.profiles (id) on delete cascade,
  brand_id smallint not null references public.brands (id),
  model_id integer references public.phone_models (id),
  custom_model text check (custom_model is null or char_length(custom_model) between 2 and 80),
  variant text check (variant is null or char_length(variant) <= 60),
  title text not null default '' check (char_length(title) between 3 and 120),
  description text not null default '' check (char_length(description) <= 5000),
  storage_gb integer check (storage_gb is null or storage_gb between 1 and 4096),
  ram_gb integer check (ram_gb is null or ram_gb between 1 and 64),
  color text check (color is null or char_length(color) <= 40),
  condition public.listing_condition,
  battery_health_status public.battery_health_status not null default 'unknown',
  battery_health smallint check (battery_health is null or battery_health between 1 and 100),
  device_checks jsonb not null default '{}' check (public.valid_device_checks(device_checks)),
  network_lock public.network_lock_status not null default 'unknown',
  accessories text[] not null default '{}' check (
    accessories <@ array['original_box', 'charger', 'cable', 'receipt', 'warranty_card', 'case', 'earphones', 'screen_protector']
  ),
  defects text check (defects is null or char_length(defects) <= 1000),
  warranty_details text check (warranty_details is null or char_length(warranty_details) <= 300),
  currency char(3) not null default 'GHS' check (currency = 'GHS'),
  -- Minor units (pesewas). GH₵1.00 .. GH₵1,000,000.00
  price_minor bigint check (price_minor is null or price_minor between 100 and 100000000),
  is_negotiable boolean not null default false,
  available_for_sale boolean not null default true,
  open_to_swap boolean not null default false,
  swap_notes text check (swap_notes is null or char_length(swap_notes) <= 500),
  -- Largest cash top-up the seller would add or accept in a swap (indicative only).
  swap_max_cash_minor bigint check (swap_max_cash_minor is null or swap_max_cash_minor between 0 and 100000000),
  region_id smallint references public.regions (id),
  city text check (city is null or char_length(city) between 2 and 80),
  area text check (area is null or char_length(area) <= 80),
  status public.listing_status not null default 'draft',
  moderation_status public.moderation_status not null default 'not_submitted',
  published_at timestamptz,
  status_changed_at timestamptz not null default now(),
  search_vector tsvector,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint listing_has_model check (model_id is not null or custom_model is not null),
  constraint listing_sale_or_swap check (available_for_sale or open_to_swap),
  constraint listing_battery_consistent check ((battery_health_status = 'reported') = (battery_health is not null)),
  constraint listing_complete_unless_draft check (
    status = 'draft'
    or (condition is not null and price_minor is not null and region_id is not null and city is not null)
  )
);

